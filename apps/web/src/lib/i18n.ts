export function locationReasonLabel(language: Language, reason?: string): string | undefined {
  if (!reason || language === "en") return reason;
  return locationReasonLabels[reason] ?? reason;
}

export function weekdayLabels(language: Language): string[] {
  return language === "ms" ? ["Ahd", "Isn", "Sel", "Rab", "Kha", "Jum", "Sab"] : ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
}
